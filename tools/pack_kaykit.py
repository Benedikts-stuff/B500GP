"""Packs a selection of KayKit Forest Nature Pack models (CC0, Kay Lousberg) into assets/pack_kaykit.js.
The colour atlas is recoloured for an alpine look: darker fir green, grey-brown bark, warm limestone grey."""
import json, base64, io, os, sys, zipfile, re
from PIL import Image
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ZIP = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'assets', 'KayKit_Forest_Nature_Pack_1.0_FREE.zip')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'assets', 'pack_kaykit.js')
PICK = ['Tree_4_A', 'Tree_4_B', 'Tree_4_C', 'Tree_3_A', 'Tree_3_B', 'Tree_3_C', 'Tree_Bare_2_B', 'Tree_Bare_2_C',
        'Rock_1_G', 'Rock_1_H', 'Rock_1_J', 'Rock_1_K', 'Rock_1_M', 'Rock_1_N', 'Rock_1_P', 'Rock_2_E', 'Rock_2_F', 'Rock_2_G', 'Rock_2_H',
        'Rock_3_E', 'Rock_3_G', 'Rock_3_J', 'Rock_3_K', 'Rock_3_M', 'Rock_3_Q', 'Rock_3_R',
        'Grass_1_A', 'Grass_1_B', 'Grass_1_C', 'Grass_2_A', 'Grass_2_B', 'Grass_2_C', 'Bush_1_C', 'Bush_1_E', 'Bush_4_B', 'Bush_4_C', 'Bush_4_D']

z = zipfile.ZipFile(ZIP)
names = z.namelist()
def find(suffix):
    for n in names:
        if n.endswith('/gltf/' + suffix) or n.endswith('/Assets/gltf/' + suffix): return n
    raise KeyError(suffix)

# ---- recoloured atlas: each swatch in the left column is a vertical gradient
atlas = np.asarray(Image.open(io.BytesIO(z.read(find('forest_texture.png')))).convert('RGB'), np.float32)
H = atlas.shape[0]; sw = H // 4
grads = [((112, 152, 74), (22, 54, 36)),     # foliage / grass
         ((122, 92, 70), (62, 44, 34)),      # bark
         ((198, 194, 184), (112, 108, 102)), # rock
         None]
out = atlas.copy()
for k, g in enumerate(grads):
    if not g: continue
    t = np.linspace(0, 1, sw)[:, None, None]
    col = np.array(g[0], np.float32) * (1 - t) + np.array(g[1], np.float32) * t
    out[k * sw:(k + 1) * sw, :H // 8] = col
im = Image.fromarray(out.clip(0, 255).astype(np.uint8)).resize((256, 256), Image.LANCZOS)
b = io.BytesIO(); im.save(b, 'PNG', optimize=True)
lines = ['/* generated by tools/pack_kaykit.py from the KayKit Forest Nature Pack (CC0, Kay Lousberg) */', '(function(P){',
         'P.tex["kaykit_atlas"]="data:image/png;base64,' + base64.b64encode(b.getvalue()).decode() + '";']
tris = 0
for name in PICK:
    j = json.loads(z.read(find(name + '_Color1.gltf')))
    binname = j['buffers'][0]['uri']; bin_ = z.read(find(binname)); del j['buffers'][0]['uri']
    for img in j.get('images', []): img['uri'] = 'tex:kaykit_atlas'; img.pop('mimeType', None)
    for m in j.get('materials', []): m['name'] = 'kk_' + name.split('_')[0].lower()
    tris += sum(j['accessors'][p['indices']]['count'] // 3 for me in j['meshes'] for p in me['primitives'])
    lines.append('P.models["kaykit/%s"]={json:%s,bin:"%s"};' % (name, json.dumps(j, separators=(',', ':')), base64.b64encode(bin_).decode()))
lines.append('})(window.APEX_PACK=window.APEX_PACK||{tex:{},models:{}});')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(len(PICK), 'models', tris, 'tris', os.path.getsize(OUT), 'bytes')
