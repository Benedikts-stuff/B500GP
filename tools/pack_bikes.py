"""Pack Blender bike exports (blender/bike_<variant>_<part>.glb) into assets/pack_bike.js.
Run from the Apex folder after tools/blender_bike.py has exported a variant:
    python3 tools/pack_bikes.py super            # add or replace only these variants
Variants you don't name keep exactly what is already in the pack."""
import base64, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.path.join(ROOT, 'assets', 'pack_bike.js')
PARTS = ('body', 'front', 'wheelF', 'wheelR')
MOVING = ('fork', 'swing', 'shockU', 'shockL', 'spring', 'decalR', 'decalL')     # only bikes with working suspension have these (tools/blender_duetto.py)
names = sys.argv[1:]
if not names: raise SystemExit('usage: python3 tools/pack_bikes.py <variant> [<variant> ...]')

entries = {}
if os.path.exists(PACK):
    for k, v in re.findall(r'P\.models\["([^"]+)"\]=\{"glb":"([A-Za-z0-9+/=]+)"\}', open(PACK).read()): entries[k] = v
for v in names:
    for part in PARTS:
        fn = os.path.join(ROOT, 'blender', 'bike_%s_%s.glb' % (v, part))
        if not os.path.exists(fn): raise SystemExit('missing ' + fn)
        entries['bike/%s_%s' % (v, part)] = base64.b64encode(open(fn, 'rb').read()).decode()
    for part in MOVING:
        fn = os.path.join(ROOT, 'blender', 'bike_%s_%s.glb' % (v, part))
        if os.path.exists(fn): entries['bike/%s_%s' % (v, part)] = base64.b64encode(open(fn, 'rb').read()).decode()
        else: entries.pop('bike/%s_%s' % (v, part), None)
variants = sorted({k.split('/')[1].rsplit('_', 1)[0] for k in entries})
out = ['/* generated by tools/pack_bikes.py: Blender-made bikes (tools/blender_bike.py, VARIANT %s) - body, steered front, wheels; AO baked into vertex colours */' % '|'.join(variants),
       '(function(P){']
for k in sorted(entries): out.append('P.models["%s"]={"glb":"%s"};' % (k, entries[k]))
out.append('})(window.APEX_PACK=window.APEX_PACK||{tex:{},models:{}});')
open(PACK, 'w').write('\n'.join(out) + '\n')
print('packed', names, '- pack now holds', variants)
