"""Pack the Blender rider parts (blender/rider_<part>.glb, from tools/blender_rider.py) into assets/pack_rider.js.
Run from anywhere:  python3 tools/pack_rider.py"""
import base64, glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['/* generated by tools/pack_rider.py: Blender-made rider parts (tools/blender_rider.py); AO baked into vertex colours */', '(function(P){']
names = []
for fn in sorted(glob.glob(os.path.join(ROOT, 'blender', 'rider_*.glb'))):
    n = os.path.basename(fn)[6:-4]; names.append(n)
    out.append('P.models["rider/%s"]={"glb":"%s"};' % (n, base64.b64encode(open(fn, 'rb').read()).decode()))
out.append('})(window.APEX_PACK=window.APEX_PACK||{tex:{},models:{}});')
open(os.path.join(ROOT, 'assets', 'pack_rider.js'), 'w').write('\n'.join(out) + '\n')
print('packed rider parts:', names)
